#!/usr/bin/env python3
"""修論の正式版（docs/研究応用/修論ドラフト/）の本文から話し言葉を拾う。

2026-10-23 新設（ユーザー「なので は話し言葉、〜であるためにする。評価するしかない も、評価する方針を取る でいい。
あなたも話し言葉を注意している感じだったけど抜けがあるので気をつけて」）。
文体の基準は docs/研究応用/執筆/わかりにくい文の判定.md の「0. 文体の基準」。散文の基準は破られるので検査にした（CLAUDE.md §5-1-2）。

見るのは PDF に入る本文だけ（「## 執筆メモ」以降・行頭が > の引用・コードブロック〔付録A のプロンプト全文〕を除く）。
口語版（執筆/修論_口語版/）は話し言葉で書く版なので見ない。

2026-11-02 追加（ユーザー「検査が拾わない型を、正規表現で書けるものは足す」。洗い出しは 執筆/文体の指摘_20261102.md）:
  話し言葉に「そもそも・〜ておく・〜わけではない」、ほかに 4 つの区分を足した。
  和語の動詞 — 0 節 ② の「漢語のサ変動詞を使う」。確かめる・返す・届く・持ち込む・寄せる・作る・決まる・成り立つ・使う・
               小さめに出る・読んだ（順位）。語の選び方の全部ではなく、本文で実際に出て、漢語に置き換えられたものだけ
  用語の揺れ — 1 つの概念に本文が決めた呼び名がある語（共設計 → co-design、判定器 → 検証エンジン、罰 → ペナルティ、
               ボーン → 骨、修正指針・指針 → 助言〔定義の「修正指針（以下、助言）」と形態の名前「指針の N 倍」は除く〕）
  段落のラベル — 型 20（段落の頭の、名詞だけの太字のラベル「**物理の値**。」）
  文末 — 「〜ことになる」（結論を事実の形で言わない）
  拾わない型（人が読む）: 和語で短く切った文の連続（check_long_sentences.py の平均字数を参考に）、主語のねじれ、
  「すなわち」の重ね言い（型 5）、指示語の先（型 3）。
  行番号はコードブロックを空行に置き換えて保つ（以前は消していたので、付録A のコードブロックより後の行番号がずれた）。

  python3 scripts/check_colloquial.py            # 出た行を並べる。0 件なら終了コード 0
  python3 scripts/check_colloquial.py --reproduce # 既知の話し言葉・和語・用語・ラベル・文末を拾えるかを確かめる
"""
import re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DRAFT = ROOT / 'docs' / '研究応用' / '修論ドラフト'
FILES = sorted(DRAFT.glob('第*.md')) + sorted(DRAFT.glob('付録*.md')) + [DRAFT / '要旨.md']

# (話し言葉, 書き言葉の言い換え)。語の途中に当たらないよう、前後を絞ったものがある
RULES = [
    (r'なので', '〜であるため・〜のため'),
    (r'しかない', '〜する方針を取る・〜する必要がある'),
    (r'けれど|けど', '〜が'),
    (r'(?:^|。)\s*(?:でも|だから|なのに|ということは)、', 'しかし・したがって・それにもかかわらず'),
    (r'ちゃんと', '正しく・確実に'),
    (r'すごく|とても|かなり', '（程度は数値で言う）'),
    (r'ちょっと|いろいろ|たくさん|どんどん', '（量は数値で言う）'),
    (r'やってみ', '実行する・試行する'),
    (r'じゃない|じゃなく', 'ではない・ではなく'),
    (r'みたいな|みたいに|っていう|なんて', '〜のような・〜という'),
    (r'ですが|です。|ます。|でした。|ました。', 'である調'),
    (r'そもそも', '（削る。「〜できない」で足りる）'),
    (r'て(?:おく|おき|おい)', '〜する（「述べておく」→「述べる」）'),
    (r'わけ(?:では|でも)', '〜とは限らない・〜ではない'),
]

# (区分, パターン, 言い換え)。RULES は区分「話し言葉」として扱う
EXTRA = [
    # 和語の動詞 → 漢語のサ変動詞（判定 md の 0 節 ②）。折り返す・繰り返す・跳ね返る・引き寄せる・押し寄せるは除く
    ('和語の動詞', r'確かめ', '確認する・検証する'),
    ('和語の動詞', r'(?<![りね見引裏])返[さしすせそ]', '出力する・提示する'),
    ('和語の動詞', r'届[かきくけこい]', '到達する'),
    ('和語の動詞', r'持ち込', '入力する・与える'),
    ('和語の動詞', r'(?<![引押])寄せ[るたて]', '接近させる・近づける'),
    ('和語の動詞', r'作[らりるれろっ]', '作成する・構築する・生成する・求める'),
    ('和語の動詞', r'決ま[らりるれろっ]', '定まる・決定される'),
    ('和語の動詞', r'成り立', '成立する'),
    ('和語の動詞', r'使[わいうえおっ]', '用いる・使用する・活用する'),
    ('和語の動詞', r'(?:め|く)に?出(?:る|や|た)', '〜と算出される・〜となる'),
    ('和語の動詞', r'読んだ', '〜時点の・〜で判断した'),
    # 用語の揺れ。本文が決めた呼び名にそろえる
    ('用語', r'共設計', 'co-design（本文の呼び名）'),
    ('用語', r'判定器', '検証エンジン（1.2 節の呼び名）'),
    ('用語', r'罰', 'ペナルティ（第3章前段 3.2 節の呼び名）'),
    # 2026-11-02 ユーザー決定「骨にそろえる」「修正指針（以下、助言）で定義」。定義の 1 回（要旨と第1章 1.2）だけを許す。
    # 形態の名前「指針の 1.99 倍・2.11 倍」（図 4.1 で定義）は除く
    ('用語', r'ボーン', '骨（3.9 節で定義する呼び名）'),
    ('用語', r'修正指針(?!（以下、助言）)', '助言（要旨と第1章 1.2 で「修正指針（以下、助言）」と定義する）'),
    ('用語', r'(?<!修正)指針(?!（以下|の ?[0-9.]+ ?倍)', '助言（「指針の 1.99 倍」のような形態の名前は残す）'),
    # 判定 md の型 20: 段落の頭の、名詞だけの太字のラベル
    ('段落のラベル', r'^\*\*[^*]{1,15}\*\*。', '段落の最初の文を主題文にする（型 20）'),
    ('文末', r'ことになる', '（削る。「〜が入れ替わった」と事実で言う）'),
]
ALL_RULES = [('話し言葉', p, a) for p, a in RULES] + EXTRA

def body(path: Path) -> str:
    t = re.split(r'^## 執筆メモ', path.read_text(encoding='utf-8'), flags=re.M)[0]
    # コードブロックは空行に置き換える（行番号を保つ）
    t = re.sub(r'^```.*?^```', lambda m: '\n' * m.group(0).count('\n'), t, flags=re.M | re.S)
    return '\n'.join('' if l.startswith('>') else l for l in t.split('\n'))

def scan(text: str):
    for n, line in enumerate(text.split('\n'), 1):
        for cat, pat, alt in ALL_RULES:
            for m in re.finditer(pat, line):
                yield n, cat, m.group(0).strip('。、 '), alt, line[max(0, m.start() - 25):m.end() + 15]

def main():
    if '--reproduce' in sys.argv:
        sample = ('得られるのは大まかな情報だけなので、事後に評価するしかない。でも、ちゃんと動く。\n'
                  'そもそも実行できない。範囲について述べておく。動かしたわけではない。\n'
                  '成り立つかは確かめられていない。目標に届かなかった。利用者が持ち込んだ形態。先端を寄せる速さ。\n'
                  '共設計を開始し、判定器の出力を読む。罰を与える。ボーンを並べる。\n'
                  '修正指針（以下、助言）として提示する。修正指針を得る。指針の倍率。指針の 1.99 倍の形態。\n'
                  '**物理の値**。以降の実験は表の値で行う。\n'
                  '順位が入れ替わったことになる。\n'
                  '腕を折り返した姿勢を繰り返し、跳ね返る。')
        found = {w for _, _, w, _, _ in scan(sample)}
        want = {'なので', 'しかない', 'でも', 'ちゃんと', 'そもそも', 'ておく', 'わけでは',
                '成り立', '確かめ', '届か', '持ち込', '寄せる', '共設計', '判定器', '罰',
                '**物理の値**', 'ことになる', 'ボーン', '修正指針', '指針'}
        # 折り返す・繰り返す・跳ね返る、定義の「修正指針（以下、助言）」と形態の名前「指針の 1.99 倍」を拾ってはいけない
        hits = [(w, ctx) for _, _, w, _, ctx in scan(sample)]
        wrong = {w for w, _ in hits if w.startswith('返')}
        wrong |= {'定義を拾った' for w, ctx in hits if w == '修正指針' and '（以下' in ctx and ctx.count('修正指針') == 1}
        n_shishin = sum(1 for w, _ in hits if w in ('修正指針', '指針'))
        if n_shishin != 2:   # 「修正指針を得る」と「指針の倍率」の 2 つだけ
            wrong.add(f'指針を {n_shishin} 件拾った（期待 2）')
        print('拾えた:', sorted(found), '／ 期待:', sorted(want), '／ 拾ってはいけないのに拾った:', sorted(wrong))
        sys.exit(0 if want <= found and not wrong else 1)
    total, by_cat = 0, {}
    for f in FILES:
        for n, cat, w, alt, ctx in scan(body(f)):
            total += 1
            by_cat[cat] = by_cat.get(cat, 0) + 1
            print(f'{f.name}:{n}: [{cat}]「{w}」→ {alt}\n    …{ctx}…')
    if total:
        print(f'\n{total} 件（' + '・'.join(f'{c} {k}' for c, k in by_cat.items()) + '）')
    else:
        print('✅ 話し言葉・和語の動詞・用語の揺れ・段落のラベル・冗長な文末は見つからなかった。')
    sys.exit(1 if total else 0)

if __name__ == '__main__':
    main()
